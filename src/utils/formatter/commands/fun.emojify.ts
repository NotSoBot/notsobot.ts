const DEFAULT_BACKGROUND = '\u{1F602}';
const DEFAULT_FOREGROUND = '\u{1F171}\u{FE0F}';
const MAX_TEXT_LENGTH = 32;
const REGEX_CUSTOM_EMOJI = /^<a?:\w{2,32}:\d+>$/;

export const COMMAND_ID = 'fun.emojify';

export interface CommandArgs {
  text: string,
  vertical?: boolean,
}

function isEmoji(value: string): boolean {
  if (REGEX_CUSTOM_EMOJI.test(value)) {
    return true;
  }
  const emojis = onlyEmoji(value);
  return !!emojis && emojis.length === 1 && emojis[0] === value;
}

// the first two emojis are the background and foreground, the rest of the words are the text
export function parseText(value: string): {background: string, foreground: string, text: Array<string>} {
  const emojis: Array<string> = [];
  const words: Array<string> = [];
  for (let word of value.split(/\s+/)) {
    if (!word) {
      continue;
    }
    if (emojis.length < 2 && isEmoji(word)) {
      emojis.push(word);
    } else {
      words.push(word);
    }
  }
  const [ background = DEFAULT_BACKGROUND, foreground = DEFAULT_FOREGROUND ] = emojis;
  return {background, foreground, text: Array.from(words.join(' ')).slice(0, MAX_TEXT_LENGTH)};
}

export async function createMessage(
  context: Command.Context | Interaction.InteractionContext,
  args: CommandArgs,
) {
  const { background, foreground, text } = parseText(args.text);
  const glyphs = text.map((character) => GLYPHS[character.toUpperCase()] || GLYPHS.nochar);
  const draw = (row: string) => Array.from(row, (bit) => (bit === '1') ? foreground : background).join('');

  const lines: Array<string> = [];
  if (args.vertical) {
    for (let glyph of glyphs) {
      lines.push(...glyph.map(draw));
    }
  } else {
    for (let i = 0; i < 7; i++) {
      lines.push(glyphs.map((glyph) => draw(glyph[i])).join(''));
    }
  }

  // too long for a message gets uploaded as a file by displayReply
  return displayReply(context, {description: lines.join('\n')});
}
